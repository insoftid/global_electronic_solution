        <script>
            (function(){
                const grid = document.getElementById('projects-grid');
                const paginationContainer = document.getElementById('projects-pagination');
                const cards = Array.from(grid.querySelectorAll('.project-card'));
                const total = {{ count($projects) }};

                let perPage = computePerPage();
                let currentPage = 1;

                function computePerPage(){
                    const w = window.innerWidth;
                    // mobile: below 640px -> max 6, tablet & laptop (>=640) -> max 9
                    return (w < 640) ? 6 : 9;
                }

                function render(){
                    perPage = computePerPage();
                    const totalPages = Math.max(1, Math.ceil(total / perPage));
                    if (currentPage > totalPages) currentPage = totalPages;

                    const start = (currentPage - 1) * perPage;
                    const end = start + perPage;

                    cards.forEach((card, idx) => {
                        if (idx >= start && idx < end) {
                            card.classList.remove('hidden');
                        } else {
                            card.classList.add('hidden');
                        }
                    });

                    renderPaginationControls(totalPages);
                }

                function renderPaginationControls(totalPages){
                    paginationContainer.innerHTML = '';

                    if (totalPages <= 1) return; // no controls when single page

                    const prev = makeBtn('Prev', currentPage === 1);
                    prev.addEventListener('click', () => { if (currentPage > 1) { currentPage--; render(); scrollToGrid(); } });
                    paginationContainer.appendChild(prev);

                    // show up to 7 page buttons (smart truncation)
                    const maxButtons = 7;
                    let startPage = 1;
                    let endPage = totalPages;
                    if (totalPages > maxButtons) {
                        const half = Math.floor(maxButtons / 2);
                        startPage = Math.max(1, currentPage - half);
                        endPage = startPage + maxButtons - 1;
                        if (endPage > totalPages) { endPage = totalPages; startPage = endPage - maxButtons + 1; }
                    }

                    if (startPage > 1) {
                        const first = makeBtn('1', false);
                        first.addEventListener('click', () => { currentPage = 1; render(); scrollToGrid(); });
                        paginationContainer.appendChild(first);
                        if (startPage > 2) {
                            const dot = document.createElement('span'); dot.textContent = '...'; dot.className = 'px-2 text-gray-500'; paginationContainer.appendChild(dot);
                        }
                    }

                    for (let p = startPage; p <= endPage; p++){
                        const btn = makeBtn(String(p), p === currentPage);
                        btn.addEventListener('click', () => { currentPage = p; render(); scrollToGrid(); });
                        paginationContainer.appendChild(btn);
                    }

                    if (endPage < totalPages) {
                        if (endPage < totalPages - 1) {
                            const dot = document.createElement('span'); dot.textContent = '...'; dot.className = 'px-2 text-gray-500'; paginationContainer.appendChild(dot);
                        }
                        const last = makeBtn(String(totalPages), false);
                        last.addEventListener('click', () => { currentPage = totalPages; render(); scrollToGrid(); });
                        paginationContainer.appendChild(last);
                    }

                    const next = makeBtn('Next', currentPage === totalPages);
                    next.addEventListener('click', () => { if (currentPage < totalPages) { currentPage++; render(); scrollToGrid(); } });
                    paginationContainer.appendChild(next);
                }

                function makeBtn(text, disabledOrActive){
                    const b = document.createElement('button');
                    b.type = 'button';
                    b.className = 'px-3 py-1 rounded-md border border-gray-200 bg-secondary text-white hover:bg-primary';
                    if (disabledOrActive) {
                        b.className = 'px-3 py-1 rounded-md border border-gray-300 bg-secondary/50 text-white cursor-default';
                        b.disabled = true;
                    }
                    b.textContent = text;
                    return b;
                }

                function scrollToGrid(){
                    // smooth scroll grid into view on page change (mobile UX)
                    if (grid) grid.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }

                // initial render
                render();

                // re-render on resize with debounce
                let resizeTimer = null;
                window.addEventListener('resize', function(){
                    clearTimeout(resizeTimer);
                    resizeTimer = setTimeout(() => { perPage = computePerPage(); currentPage = 1; render(); }, 150);
                });

            })();
        </script>

